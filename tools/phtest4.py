def build(j, sysp, ph, use_ex):
    msgs = [{"role": "system", "content": sysp}]
    parts = [p for p in (j.get("description"), j.get("personality"),
                         j.get("scenario")) if p and p.strip()]
    msgs.append({"role": "system", "content": "\n\n".join(parts)})
    ex = (j.get("mes_example") or "").strip()
    if use_ex and ex:
        msgs.append({"role": "system", "content": "【对话示例】\n" + ex})
    msgs.append({"role": "assistant", "content": j["first_mes"]})
    msgs.append({"role": "system", "content": ph})
    msgs.append({"role": "user", "content": USER1})
    return msgs


def call(msgs, seed, max_tokens=700):
    body = {"model": MODEL, "messages": msgs, "temperature": 1.0,
            "top_p": 0.95, "max_tokens": max_tokens, "seed": seed}
    req = urllib.request.Request(
        API, data=json.dumps(body).encode("utf-8"),
        headers={"Content-Type": "application/json",
                 "Authorization": "Bearer " + KEY})
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=300) as r:
        d = json.loads(r.read().decode("utf-8"))
    return d["choices"][0]["message"]["content"], time.time() - t0


def metrics(txt):
    lines = [l for l in txt.splitlines() if l.strip()]
    quotes = [l for l in lines if l.lstrip().startswith(">")]
    naked = [l for l in lines
             if l.lstrip()[:1] in ('"', '\u201c', '\u300c')
             and not l.lstrip().startswith(">")]
    return {
        "台词行": len(quotes),
        "漏>": len(naked),
        "行尾挂动作": len([l for l in quotes if "*" in l]),
        "反引号": txt.count("`"),
        "韩文": len(KOR.findall(txt)),
        "英文词": len(re.findall(r"[A-Za-z]{3,}", txt)),
        "字数": len(re.sub(r"\s", "", txt)),
        "首轮失手": 1 if not quotes else 0,
    }


def main():
    if len(sys.argv) < 2:
        print("用法: python tools/phtest4.py <变体名|all|list> [重复次数]")
        return
    name = sys.argv[1]
    if name == "list":
        for k, (s, p, e) in VARIANTS.items():
            print(f"{k:<6} sys={len(s):>4}  ph={len(p):>4}  "
                  f"mes_example={'有' if e else '无'}")
        return
    reps = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    if name.startswith("@"):
        parts = name[1:].split(":")
        global CARD, USER1
        CARD, USER1 = CARDS[parts[0]]
        name = parts[1]

    names = list(VARIANTS) if name == "all" else [name]

    j = load()
    report = []
    for n in names:
        sysp, ph, use_ex = VARIANTS[n]
        msgs = build(j, sysp, ph, use_ex)
        total = sum(len(m["content"]) for m in msgs)
        print("=" * 78)
        print(f"### 变体 {n}  |  提示词总量 {total} 字符  |  "
              f"sys {len(sysp)} + ph {len(ph)} + mes_example "
              f"{'有' if use_ex else '无'}")
        print("=" * 78)
        for i in range(reps):
            try:
                txt, dt = call(msgs, seed=4000 + i)
            except Exception as e:
                print(f"[{i+1}] 失败: {e}")
                continue
            m = metrics(txt)
            print(f"\n---------- [{n} #{i+1}] ({dt:.1f}s) {m} ----------")
            print(txt)
            report.append((n, i + 1, m, txt, total))
    print("\n" + "=" * 78)
    print("### 汇总")
    print(f"{'变体':<6}{'#':>3}{'歌词行':>7}{'漏>':>6}{'行尾动作':>9}"
          f"{'反引号':>7}{'韩文':>6}{'英文词':>7}{'字数':>7}{'首轮失手':>9}")
    for n, i, m, _, _ in report:
        print(f"{n:<6}{i:>3}{m['台词行']:>7}{m['漏>']:>6}{m['行尾挂动作']:>9}"
              f"{m['反引号']:>7}{m['韩文']:>6}{m['英文词']:>7}{m['字数']:>7}"
              f"{m['首轮失手']:>9}")
    json.dump([{"variant": n, "run": i, "metrics": m, "text": x, "prompt_len": t}
               for n, i, m, x, t in report],
              open("tools/out/phtest4_runs.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print("\n原始文本已存 tools/out/phtest4_runs.json")


if __name__ == "__main__":
    main()
